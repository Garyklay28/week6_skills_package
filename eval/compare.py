#!/usr/bin/env python3
"""Score A and B with the same checker and write eval/COMPARISON.md.

Usage (from the repo root):  python3 eval/compare.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "B_with_skills" / "scripts"))
from subtitle_check import check  # noqa: E402

SOURCE = ROOT / "input" / "字幕文件中文.txt"
TERMS = json.loads((ROOT / "B_with_skills" / "scripts" / "eval_terms.json").read_text(encoding="utf-8"))
RUNS = {"A (no skills)": ROOT / "A_no_skills" / "result_en.txt",
        "B (skill package)": ROOT / "B_with_skills" / "result_en.txt"}

# Lower is better for every metric except these.
HIGHER_BETTER = {"contractions"}
SKIP = {"lines", "source_lines"}


def main():
    results = {name: check(SOURCE, path, TERMS) for name, path in RUNS.items()}
    names = list(results)
    a, b = (results[n] for n in names)

    out = ["# A vs B: checker comparison", "",
           "Generated by `python3 eval/compare.py`. Both files are scored by the same",
           "`B_with_skills/scripts/subtitle_check.py` with the same `eval_terms.json`.", "",
           f"| metric | {names[0]} | {names[1]} |", "|---|---|---|",
           f"| hard checks | {'PASS' if a['ok'] else 'FAIL'} | {'PASS' if b['ok'] else 'FAIL'} |"]
    for k in a["metrics"]:
        if k in SKIP:
            continue
        va, vb = a["metrics"][k], b["metrics"][k]
        better = None
        if va != vb:
            better = (vb > va) if k in HIGHER_BETTER else (vb < va)
        mark = "" if better is None else (" ✅B" if better else " ✅A")
        out.append(f"| {k} | {va} | {vb}{mark} |")

    for name, r in results.items():
        out += ["", f"## {name}", "", "Hard:"] + ([f"- {h}" for h in r["hard"]] or ["- none"])
        out += ["", "Soft:"] + ([f"- {s}" for s in r["soft"]] or ["- none"])

    out += ["", "## Term renderings", "", f"| term | {names[0]} | {names[1]} |", "|---|---|---|"]
    for t in TERMS:
        cells = []
        for r in (a, b):
            rend = r["terms"][t]["renderings"]
            cells.append("; ".join(f"{k} {v}" for k, v in rend.items()) or "-")
        out.append(f"| {t} | {cells[0]} | {cells[1]} |")

    out += ["", "## Line by line", "", "Lines where A and B differ. `*` = over 42 chars.", "",
            f"| # | 中文 | {names[0]} | {names[1]} |", "|---|---|---|---|"]
    esc = lambda s: s.replace("|", "\\|")
    for ra, rb in zip(a["rows"], b["rows"]):
        if ra["en"] == rb["en"]:
            continue
        fa = esc(ra["en"]) + (" *" if ra["chars"] > 42 else "")
        fb = esc(rb["en"]) + (" *" if rb["chars"] > 42 else "")
        out.append(f"| {ra['n']} | {esc(ra['zh'])} | {fa} | {fb} |")

    dest = ROOT / "eval" / "COMPARISON.md"
    dest.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {dest.relative_to(ROOT)}")
    for n, r in results.items():
        print(f"{n}: {'PASS' if r['ok'] else 'FAIL'} {r['metrics']}")


if __name__ == "__main__":
    main()
